import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import {PGlite} from '@electric-sql/pglite';

test('remembered session permissions, disconnect generations, household changes and rolling import receipts', async t => {
  const db = new PGlite(); t.after(() => db.close()); let checks = 0;
  const q = async (sql,params=[]) => (await db.query(sql,params)).rows;
  const fail = async (fn,re) => {await assert.rejects(fn,re); checks++;};
  const equal = (a,b) => {assert.deepEqual(a,b); checks++;};
  const scalar = async (sql,value) => equal(Object.values((await q(sql))[0])[0],value);
  await db.exec(`CREATE ROLE anon; CREATE ROLE authenticated; CREATE ROLE service_role; CREATE SCHEMA auth;
    GRANT USAGE ON SCHEMA auth TO anon,authenticated;
    CREATE TABLE auth.users(id uuid PRIMARY KEY,raw_user_meta_data jsonb);
    CREATE FUNCTION auth.uid() RETURNS uuid LANGUAGE sql STABLE AS $$SELECT nullif(current_setting('request.jwt.claim.sub',true),'')::uuid$$;
    CREATE PUBLICATION supabase_realtime;
    -- PGlite cannot load native Vault. This synthetic adapter tests calls/cleanup, not encryption.
    CREATE SCHEMA vault; CREATE TABLE vault.secrets(id uuid PRIMARY KEY DEFAULT gen_random_uuid(),secret text);
    CREATE VIEW vault.decrypted_secrets AS SELECT id,secret AS decrypted_secret FROM vault.secrets;
    CREATE FUNCTION vault.create_secret(new_secret text,new_name text DEFAULT NULL,new_description text DEFAULT NULL,new_key_id uuid DEFAULT NULL) RETURNS uuid LANGUAGE sql AS $$INSERT INTO vault.secrets(secret) VALUES(new_secret) RETURNING id$$;`);
  const schema = await fs.readFile(new URL('../supabase_schema.sql',import.meta.url),'utf8');
  const migration = await fs.readFile(new URL('../supabase/migrations/20261019112835_prior_remembered_session.sql',import.meta.url),'utf8');
  equal(schema.split('-- 17. Remembered Priorbank session (2026-10-19)')[1].trim(),migration.trim());
  await db.exec(schema); await db.exec(migration); checks++;
  await db.exec('GRANT USAGE ON SCHEMA public TO anon,authenticated; GRANT SELECT ON public.transactions TO authenticated;');
  const a='11111111-1111-4111-8111-111111111111',b='22222222-2222-4222-8222-222222222222';
  await q(`INSERT INTO auth.users VALUES($1,'{"household_action":"create","household_name":"A"}'),($2,'{"household_action":"create","household_name":"B"}')`,[a,b]);
  const state = async (who,action,data={}) => (await q('SELECT prior_connection_state($1,$2,$3) AS v',[who,action,data]))[0].v;
  const session = {token:'SYNTHETIC_TOKEN',client:'SYNTHETIC_CLIENT',userSession:'SYNTHETIC_SESSION'};
  for (const role of ['anon','authenticated']) {
    await db.exec(`SET ROLE ${role}`);
    await fail(() => state(a,'load'),/permission denied/);
    await fail(() => q('SELECT * FROM finance_private.prior_connections'),/permission denied/);
    await fail(() => q('SELECT * FROM vault.decrypted_secrets'),/permission denied/);
    await db.exec('RESET ROLE');
  }
  await db.exec('SET ROLE service_role');
  let meta = await state(a,'status'); equal(meta.connected,false);
  const initial = meta.revision;
  await fail(() => state(a,'save',{revision:initial,session:{...session,password:'NEVER_STORE'},loginKey:'a'.repeat(64)}),/PRIOR_CONNECTION_FORMAT/);
  meta = await state(a,'save',{revision:initial,session,loginKey:'a'.repeat(64),preview:{cards:[]}});
  equal(meta.connected,true); equal(meta.reauthRequired,false);
  assert.doesNotMatch(JSON.stringify(meta),/SYNTHETIC|session|loginKey|preview/); checks++;
  equal((await state(a,'load')).session,session);
  equal((await state(b,'status')).connected,false);
  await fail(() => state(a,'save',{revision:initial,session,loginKey:'a'.repeat(64)}),/PRIOR_CONNECTION_CHANGED/);
  const saved=meta.revision;
  equal((await state(a,'disconnect')).connected,false);
  await fail(() => state(a,'touch',{revision:saved}),/PRIOR_CONNECTION_CHANGED/);
  await fail(() => state(a,'save',{revision:saved,session,loginKey:'a'.repeat(64)}),/PRIOR_CONNECTION_CHANGED/);
  await db.exec('RESET ROLE'); await scalar('SELECT count(*)::int FROM vault.secrets',0);
  await db.exec('SET ROLE service_role');
  meta = await state(a,'status');
  meta = await state(a,'save',{revision:meta.revision,session,loginKey:'a'.repeat(64)});
  const obsolete=meta.revision;
  meta = await state(a,'save',{revision:meta.revision,session,loginKey:'a'.repeat(64)});
  await fail(() => state(a,'expire',{revision:obsolete}),/PRIOR_CONNECTION_CHANGED/);
  await db.exec('RESET ROLE'); await scalar('SELECT count(*)::int FROM vault.secrets',1);
  await db.exec('SET ROLE service_role');
  meta = await state(a,'expire',{revision:meta.revision}); equal(meta.connected,false); equal(meta.reauthRequired,true);
  meta = await state(a,'save',{revision:meta.revision,session,loginKey:'a'.repeat(64)});
  await db.exec('RESET ROLE');
  await db.exec('ALTER TABLE profiles DISABLE TRIGGER guard_profile_membership');
  await q('UPDATE profiles SET household_id=(SELECT household_id FROM profiles WHERE id=$2) WHERE id=$1',[a,b]);
  await db.exec('ALTER TABLE profiles ENABLE TRIGGER guard_profile_membership');
  await db.exec('SET ROLE service_role'); equal((await state(a,'status')).connected,false);
  await db.exec('RESET ROLE'); await scalar('SELECT count(*)::int FROM vault.secrets',0);
  await scalar("SELECT count(*)::int FROM pg_policies WHERE tablename='prior_connections'",4);
  // Rolling windows keep receipts even when old ledger rows are deleted.
  await db.exec(`SET ROLE authenticated; SELECT set_config('request.jwt.claim.sub','${a}',false);`);
  await q(`SELECT initialize_finance('{}'::uuid[])`); const [{id:account}]=await q('SELECT id FROM accounts');
  const [{today,old,recent,from}]=await q(`SELECT (now() AT TIME ZONE 'Europe/Minsk')::date::text AS today,((now() AT TIME ZONE 'Europe/Minsk')::date-20)::text AS old,((now() AT TIME ZONE 'Europe/Minsk')::date-1)::text AS recent,((now() AT TIME ZONE 'Europe/Minsk')::date-10)::text AS "from"`);
  const packet=(start,day,description='Shop') => ({format:'finapp-prior',version:1,from:start,to:day,fetchedAt:today+'T12:00:00Z',card:{sourceKey:'f'.repeat(64),title:'Card',maskedNumber:'•••• 1234',currency:'BYN',records:[{date:day,description,accountAmount:'-12.34',operationAmount:'-12.34',operationCurrency:'BYN',fee:null,source:'history'}]}});
  const preview=async p => (await q('SELECT preview_prior_import($1,$2) AS v',[account,p]))[0].v;
  const save=async (p,confirmExisting=false) => (await q('SELECT import_prior_operations($1,$2,$3) AS v',[account,p,[{index:0,categoryId:'other',confirmExisting}]]))[0].v;
  const older=packet(old,old); equal(await save(older),{imported:1,skipped:0});
  const [{id:transaction}]=await q('SELECT id FROM transactions'); await q('SELECT delete_finance_transaction($1)',[transaction]);
  const recentPacket=packet(from,recent);
  equal(await preview(recentPacket),{importedIndexes:[],linked:true,possibleIndexes:[0]});
  await fail(() => save(recentPacket),/PRIOR_CONFIRM_EXISTING/);
  equal(await save(recentPacket,true),{imported:1,skipped:0});
  equal(await save(recentPacket),{imported:0,skipped:1});
  equal(await save(older),{imported:0,skipped:1});
  await fail(() => preview(packet(from,recent,'Changed by bank')),/PRIOR_DAY_CHANGED/);
  const emptied=packet(from,recent); emptied.card.records=[];
  await fail(() => preview(emptied),/PRIOR_DAY_CHANGED/);
  await scalar('SELECT count(*)::int FROM transactions',1);
  await scalar('SELECT count(*)::int FROM prior_import_days',2);
  await db.exec('RESET ROLE'); await db.exec('SET ROLE service_role');
  const preferred=await state(a,'status'); equal(preferred.accountId,account); equal(preferred.selectedSourceKey,'f'.repeat(64));
  meta=await state(b,'status'); await state(b,'save',{revision:meta.revision,session,loginKey:'b'.repeat(64)});
  await db.exec('RESET ROLE');
  // Delete connection metadata exercises the same cleanup trigger as owner/household cascades.
  await q('DELETE FROM finance_private.prior_connections WHERE owner_id=$1',[b]);
  await scalar('SELECT count(*)::int FROM vault.secrets',0);
  t.diagnostic(`${checks} remembered-session/rolling-window SQL assertions passed (Vault adapter only)`);
});
